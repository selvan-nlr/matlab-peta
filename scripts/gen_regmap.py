#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Generate VHDL, C, Python and Markdown from the YAML register descriptions.

The register map is the contract between the RTL, the testbenches, the on-board
software and the host API.  Writing it four times by hand is how those four
drift apart, so it is written once in `regmap/*.yaml` and everything else is
generated.  CI regenerates and diffs, which makes drift a build failure rather
than a debugging session.

Usage:
    python3 scripts/gen_regmap.py            # write outputs
    python3 scripts/gen_regmap.py --check    # fail if outputs are stale
"""

from __future__ import annotations

import argparse
import dataclasses
import pathlib
import sys
import textwrap

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGMAP_DIR = ROOT / "regmap"

WARNING = "-- Generated by scripts/gen_regmap.py from regmap/{src}. Do not edit."
WARNING_C = "/* Generated by scripts/gen_regmap.py from regmap/{src}. Do not edit. */"
WARNING_PY = '"""Generated by scripts/gen_regmap.py from regmap/{src}. Do not edit."""'


# --------------------------------------------------------------------------
# Model
# --------------------------------------------------------------------------

@dataclasses.dataclass
class Field:
    name: str
    hi: int
    lo: int
    description: str = ""

    @property
    def width(self) -> int:
        return self.hi - self.lo + 1

    @property
    def mask(self) -> int:
        return ((1 << self.width) - 1) << self.lo

    @property
    def is_bit(self) -> bool:
        return self.hi == self.lo


@dataclasses.dataclass
class Register:
    name: str
    offset: int
    access: str
    reset: int = 0
    description: str = ""
    fields: list[Field] = dataclasses.field(default_factory=list)
    reserved: bool = False

    @property
    def index(self) -> int:
        return self.offset // 4

    @property
    def is_ro(self) -> bool:
        return self.access == "ro"


@dataclasses.dataclass
class Block:
    name: str
    description: str
    registers: list[Register]
    source: str

    @property
    def num_regs(self) -> int:
        return len(self.registers)

    @property
    def ro_mask(self) -> str:
        """MSB-first bit string for a std_logic_vector(NUM_REGS-1 downto 0)."""
        return "".join("1" if r.is_ro else "0" for r in reversed(self.registers))


def parse_bits(spec) -> tuple[int, int]:
    if isinstance(spec, int):
        return spec, spec
    text = str(spec).strip()
    if ":" in text:
        hi_s, lo_s = text.split(":", 1)
        hi, lo = int(hi_s, 0), int(lo_s, 0)
    else:
        hi = lo = int(text, 0)
    if hi < lo:
        raise ValueError(f"bit range {spec!r} must be written high:low")
    if hi > 31 or lo < 0:
        raise ValueError(f"bit range {spec!r} outside a 32-bit register")
    return hi, lo


def load_block(path: pathlib.Path) -> Block:
    doc = yaml.safe_load(path.read_text())
    name = doc["block"]
    registers: list[Register] = []

    for entry in doc["registers"]:
        offset = int(str(entry["offset"]), 0)
        if offset % 4:
            raise ValueError(f"{name}.{entry['name']}: offset 0x{offset:x} is not word aligned")

        fields: list[Field] = []
        used = 0
        for fspec in entry.get("fields", []):
            hi, lo = parse_bits(fspec["bits"])
            field = Field(fspec["name"], hi, lo, fspec.get("description", ""))
            if used & field.mask:
                raise ValueError(f"{name}.{entry['name']}.{field.name}: bits overlap another field")
            used |= field.mask
            fields.append(field)

        access = entry.get("access", "rw")
        if access not in ("rw", "ro"):
            raise ValueError(f"{name}.{entry['name']}: access must be 'rw' or 'ro', got {access!r}")

        registers.append(
            Register(
                name=entry["name"],
                offset=offset,
                access=access,
                reset=int(str(entry.get("reset", 0)), 0),
                description=str(entry.get("description", "")).strip(),
                fields=fields,
            )
        )

    registers.sort(key=lambda r: r.offset)

    # Fill address gaps with reserved registers so that the register index used
    # by the RTL stays equal to offset/4 with no lookup table anywhere.
    dense: list[Register] = []
    expected = 0
    for reg in registers:
        while expected < reg.offset:
            dense.append(
                Register(
                    name=f"RESERVED_{expected:02X}",
                    offset=expected,
                    access="ro",
                    description="Reserved. Reads as zero.",
                    reserved=True,
                )
            )
            expected += 4
        if reg.offset != expected:
            raise ValueError(f"{name}.{reg.name}: duplicate offset 0x{reg.offset:x}")
        dense.append(reg)
        expected += 4

    return Block(
        name=name,
        description=" ".join(str(doc.get("description", "")).split()),
        registers=dense,
        source=path.name,
    )


# --------------------------------------------------------------------------
# Emitters
# --------------------------------------------------------------------------

def wrap_comment(text: str, prefix: str, width: int = 96) -> list[str]:
    if not text:
        return []
    return [prefix + line for line in textwrap.wrap(" ".join(text.split()), width - len(prefix))]


def emit_vhdl(block: Block) -> str:
    up = block.name.upper()
    out: list[str] = [
        "-- SPDX-License-Identifier: MIT",
        WARNING.format(src=block.source),
        "--",
    ]
    out += wrap_comment(block.description, "-- ")
    out += [
        "",
        "library ieee;",
        "  use ieee.std_logic_1164.all;",
        "",
        "library work;",
        "  use work.zmix_pkg.all;",
        "",
        f"package {block.name}_regs_pkg is",
        "",
        f"  constant {up}_NUM_REGS : positive := {block.num_regs};",
        "",
        "  -- '1' marks a register the bus may not write into.",
        f'  constant {up}_RO_MASK : std_logic_vector({up}_NUM_REGS - 1 downto 0) := "{block.ro_mask}";',
        "",
        "  -- Power-on contents of the writable registers.",
        f"  constant {up}_RESET_VALS : slv32_array_t(0 to {up}_NUM_REGS - 1) :=",
        "  (",
    ]

    reset_lines = []
    for reg in block.registers:
        reset_lines.append(f'    {reg.index} => x"{reg.reset:08X}"')
    out.append(",\n".join(reset_lines))
    out += [
        "  );",
        "",
        "  -- Register word indices (byte offset / 4).",
    ]

    for reg in block.registers:
        out.append(f"  constant REG_{up}_{reg.name} : natural := {reg.index};   -- 0x{reg.offset:02X}")

    out += ["", "  -- Field positions."]
    for reg in block.registers:
        for field in reg.fields:
            base = f"{up}_{reg.name}_{field.name}"
            if field.is_bit:
                out.append(f"  constant {base}_BIT : natural := {field.lo};")
            else:
                out.append(f"  subtype {base}_R is natural range {field.hi} downto {field.lo};")
                out.append(f"  constant {base}_W : positive := {field.width};")

    out += ["", f"end package {block.name}_regs_pkg;", ""]
    return "\n".join(out)


def emit_c(block: Block) -> str:
    up = block.name.upper()
    guard = f"ZMIX_{up}_REGS_H"
    out = [
        "/* SPDX-License-Identifier: MIT */",
        WARNING_C.format(src=block.source),
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
    ]
    for reg in block.registers:
        if reg.description:
            for line in wrap_comment(reg.description, "/* "):
                out.append(line + " */")
        out.append(f"#define {up}_{reg.name}_OFFSET 0x{reg.offset:02X}u")
    out.append("")
    for reg in block.registers:
        for field in reg.fields:
            base = f"{up}_{reg.name}_{field.name}"
            out.append(f"#define {base}_SHIFT {field.lo}u")
            out.append(f"#define {base}_MASK 0x{field.mask:08X}u")
    out += [
        "",
        f"#define {up}_NUM_REGS {block.num_regs}u",
        "",
        f"#endif /* {guard} */",
        "",
    ]
    return "\n".join(out)


def emit_python(block: Block) -> str:
    out = [
        "# SPDX-License-Identifier: MIT",
        WARNING_PY.format(src=block.source),
        "",
        "from zmix.regmap import Block, Field, Register",
        "",
        "BLOCK = Block(",
        f"    name={block.name!r},",
        f"    description={block.description!r},",
        "    registers=[",
    ]
    for reg in block.registers:
        out.append("        Register(")
        out.append(f"            name={reg.name!r},")
        out.append(f"            offset=0x{reg.offset:02X},")
        out.append(f"            access={reg.access!r},")
        out.append(f"            reset=0x{reg.reset:08X},")
        out.append(f"            description={reg.description!r},")
        if reg.fields:
            out.append("            fields=[")
            for field in reg.fields:
                out.append(
                    f"                Field({field.name!r}, {field.hi}, {field.lo}, {field.description!r}),"
                )
            out.append("            ],")
        out.append("        ),")
    out += ["    ],", ")", ""]
    return "\n".join(out)


def emit_markdown(block: Block) -> str:
    out = [
        f"# `{block.name}` register map",
        "",
        f"<!-- Generated by scripts/gen_regmap.py from regmap/{block.source}. Do not edit. -->",
        "",
        block.description,
        "",
        f"{block.num_regs} registers, {block.num_regs * 4} bytes.",
        "",
        "| Offset | Name | Access | Reset | Description |",
        "| ------ | ---- | ------ | ----- | ----------- |",
    ]
    for reg in block.registers:
        desc = " ".join(reg.description.split())
        out.append(f"| `0x{reg.offset:02X}` | `{reg.name}` | {reg.access} | `0x{reg.reset:08X}` | {desc} |")

    for reg in block.registers:
        if not reg.fields:
            continue
        out += ["", f"## `{reg.name}` (`0x{reg.offset:02X}`, {reg.access})", ""]
        if reg.description:
            out += [" ".join(reg.description.split()), ""]
        out += ["| Bits | Field | Description |", "| ---- | ----- | ----------- |"]
        for field in sorted(reg.fields, key=lambda f: f.lo, reverse=True):
            bits = f"{field.hi}" if field.is_bit else f"{field.hi}:{field.lo}"
            out.append(f"| `{bits}` | `{field.name}` | {' '.join(field.description.split())} |")
    out.append("")
    return "\n".join(out)


def emit_system_python(system: dict) -> str:
    out = [
        "# SPDX-License-Identifier: MIT",
        WARNING_PY.format(src="system.yaml"),
        "",
        "from zmix.regmap import Instance",
        "",
        f"SYSTEM = {system['system']!r}",
        f"ABI = ({system['abi']['major']}, {system['abi']['minor']}, {system['abi']['patch']})",
        f"PAGE_SIZE = 0x{int(str(system['axi']['page_size']), 0):X}",
        "",
        "INSTANCES = [",
    ]
    for inst in system["instances"]:
        base = int(str(inst["base"]), 0)
        out.append(
            f"    Instance({inst['name']!r}, {inst['block']!r}, 0x{base:08X}, "
            f"{inst.get('description', '')!r}),"
        )
    out += ["]", ""]
    return "\n".join(out)


def emit_system_c(system: dict) -> str:
    out = [
        "/* SPDX-License-Identifier: MIT */",
        WARNING_C.format(src="system.yaml"),
        "#ifndef ZMIX_SYSTEM_MAP_H",
        "#define ZMIX_SYSTEM_MAP_H",
        "",
        f"#define ZMIX_ABI_MAJOR {system['abi']['major']}u",
        f"#define ZMIX_ABI_MINOR {system['abi']['minor']}u",
        f"#define ZMIX_ABI_PATCH {system['abi']['patch']}u",
        f"#define ZMIX_PAGE_SIZE 0x{int(str(system['axi']['page_size']), 0):X}u",
        "",
    ]
    for inst in system["instances"]:
        base = int(str(inst["base"]), 0)
        out.append(f"#define ZMIX_{inst['name'].upper()}_BASE 0x{base:08X}u")
    out += ["", "#endif /* ZMIX_SYSTEM_MAP_H */", ""]
    return "\n".join(out)


def emit_system_markdown(system: dict, blocks: dict[str, Block]) -> str:
    out = [
        "# Platform address map",
        "",
        "<!-- Generated by scripts/gen_regmap.py from regmap/system.yaml. Do not edit. -->",
        "",
        " ".join(str(system.get("description", "")).split()),
        "",
        f"Register-map ABI: **{system['abi']['major']}.{system['abi']['minor']}.{system['abi']['patch']}**. "
        f"Host drivers refuse a bitstream whose major version they do not know.",
        "",
        "| Base | Instance | Block | Registers | Description |",
        "| ---- | -------- | ----- | --------- | ----------- |",
    ]
    for inst in system["instances"]:
        base = int(str(inst["base"]), 0)
        block = blocks[inst["block"]]
        out.append(
            f"| `0x{base:08X}` | `{inst['name']}` | [`{block.name}`]({block.name}.md) "
            f"| {block.num_regs} | {' '.join(str(inst.get('description', '')).split())} |"
        )
    out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------
# Driver
# --------------------------------------------------------------------------

def write_out(path: pathlib.Path, text: str, check: bool, stale: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text() if path.exists() else None
    if existing == text:
        return
    if check:
        stale.append(str(path.relative_to(ROOT)))
        return
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = parser.parse_args()

    system = yaml.safe_load((REGMAP_DIR / "system.yaml").read_text())
    blocks: dict[str, Block] = {}
    for path in sorted(REGMAP_DIR.glob("*.yaml")):
        if path.name == "system.yaml":
            continue
        block = load_block(path)
        blocks[block.name] = block

    for inst in system["instances"]:
        if inst["block"] not in blocks:
            raise SystemExit(f"system.yaml references unknown block {inst['block']!r}")

    stale: list[str] = []
    for block in blocks.values():
        write_out(ROOT / "ip" / block.name / "rtl" / f"{block.name}_regs_pkg.vhd",
                  emit_vhdl(block), args.check, stale)
        write_out(ROOT / "sw" / "include" / "zmix" / f"{block.name}_regs.h",
                  emit_c(block), args.check, stale)
        write_out(ROOT / "sw" / "host" / "zmix" / "regs" / f"{block.name}.py",
                  emit_python(block), args.check, stale)
        write_out(ROOT / "docs" / "registers" / f"{block.name}.md",
                  emit_markdown(block), args.check, stale)

    write_out(ROOT / "sw" / "host" / "zmix" / "regs" / "system.py",
              emit_system_python(system), args.check, stale)
    write_out(ROOT / "sw" / "include" / "zmix" / "system_map.h",
              emit_system_c(system), args.check, stale)
    write_out(ROOT / "docs" / "registers" / "index.md",
              emit_system_markdown(system, blocks), args.check, stale)

    init = "\n".join([
        "# SPDX-License-Identifier: MIT",
        '"""Generated register definitions. Do not edit the modules in this package by hand."""',
        "",
        "from . import system",
        *[f"from . import {name}" for name in sorted(blocks)],
        "",
        "BLOCKS = {",
        *[f"    {name!r}: {name}.BLOCK," for name in sorted(blocks)],
        "}",
        "",
        '__all__ = ["BLOCKS", "system", ' + ", ".join(repr(n) for n in sorted(blocks)) + "]",
        "",
    ])
    write_out(ROOT / "sw" / "host" / "zmix" / "regs" / "__init__.py", init, args.check, stale)

    if args.check and stale:
        print("Generated files are stale; run: python3 scripts/gen_regmap.py", file=sys.stderr)
        for name in stale:
            print(f"  {name}", file=sys.stderr)
        return 1

    print(f"{len(blocks)} blocks, {sum(b.num_regs for b in blocks.values())} registers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
